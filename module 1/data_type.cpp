#include <iostream>
using namespace std;

int main(){
    //Data types in C++
    int a=10; //Integer data type
    float b=3.14; //Floating-point data type
    char c='A'; //Character data type
    bool d=true; //Boolean data type
    //Output the values
    cout<<"Integer: "<<a<<endl;
    cout<<"Float: "<<b<<endl;
    cout<<"Character: "<<c<<endl;
    cout<<"Boolean: "<<d<<endl; 
    return 0;

}
